//! Which border images exist, and finding one by what the user wrote.
//!
//! A border is named for its file: `01` is `01.png`. Any image can go on either
//! edge; the edge only decides what is done to it. Names resolve to your own
//! images first (`<config>/border/`), then to the ones built in, so a file of
//! yours shadows a bundled one of the same name. Anything with a `/` in it, or
//! ending `.png`, is a path instead.
//!
//! The folders `left_border/` and `bottom_border/` (or `down_border/`) under
//! `<config>/border/` are still read, for the edge they name, and come before
//! the loose files.

use std::path::{Path, PathBuf};

// The bundled PNGs, by name. Generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/borders.rs"));

/// Which edge an image decorates. The slot decides what is done to the image:
/// a left border is drawn as it is, and a bottom border is turned a quarter
/// clockwise so that it lies along the edge.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Slot {
    Left,
    Bottom,
}

impl Slot {
    fn key(self) -> &'static str {
        match self {
            Slot::Left => "left",
            Slot::Bottom => "bottom",
        }
    }

    /// The folders under `<config>/border/` that hold images for this edge
    /// only. Images loose in `<config>/border/` are for either.
    fn folders(self) -> &'static [&'static str] {
        match self {
            Slot::Left => &["left_border"],
            Slot::Bottom => &["bottom_border", "down_border"],
        }
    }
}

/// Where a named border comes from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Source {
    Bundled,
    File(PathBuf),
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Entry {
    pub name: String,
    pub source: Source,
}

/// `~/x` as `$HOME/x`. Nothing else is expanded.
fn expand(path: &str) -> PathBuf {
    match (path.strip_prefix("~/"), std::env::var_os("HOME")) {
        (Some(rest), Some(home)) => Path::new(&home).join(rest),
        _ => PathBuf::from(path),
    }
}

/// Whether `spec` names a file rather than a border.
fn is_path(spec: &str) -> bool {
    spec.contains('/') || spec.contains('\\') || spec.to_ascii_lowercase().ends_with(".png")
}

/// Where your own images are looked for, most specific first: the folder for
/// this edge alone, then the one for either.
fn user_dirs(config: Option<&Path>, slot: Slot) -> Vec<PathBuf> {
    let Some(base) = config.map(|c| c.join("border")) else {
        return Vec::new();
    };

    let mut dirs: Vec<PathBuf> = slot.folders().iter().map(|f| base.join(f)).collect();
    dirs.push(base);
    dirs
}

/// The PNGs directly in `dir`, by name.
fn pngs_in(dir: &Path) -> Vec<Entry> {
    let Ok(read) = std::fs::read_dir(dir) else {
        return Vec::new();
    };

    let mut found: Vec<Entry> = read
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_file())
        .filter(|p| p.extension().is_some_and(|e| e.eq_ignore_ascii_case("png")))
        .filter_map(|p| {
            let name = p.file_stem()?.to_string_lossy().into_owned();
            Some(Entry {
                name,
                source: Source::File(p),
            })
        })
        .collect();
    found.sort_by(|a, b| a.name.cmp(&b.name));
    found
}

/// Every border available for `slot`, yours first, with the built-in ones
/// that you have not shadowed after them. A name is listed once.
pub fn list(slot: Slot, config: Option<&Path>) -> Vec<Entry> {
    let mut entries: Vec<Entry> = Vec::new();

    for dir in user_dirs(config, slot) {
        for entry in pngs_in(&dir) {
            if !entries.iter().any(|e| e.name == entry.name) {
                entries.push(entry);
            }
        }
    }

    for (name, _) in BORDERS {
        if !entries.iter().any(|e| e.name == *name) {
            entries.push(Entry {
                name: (*name).to_string(),
                source: Source::Bundled,
            });
        }
    }
    entries
}

/// Why `spec` names no border: what there is to choose from.
fn unknown(slot: Slot, spec: &str, config: Option<&Path>) -> String {
    let names: Vec<String> = list(slot, config).into_iter().map(|e| e.name).collect();
    format!(
        "no {} border called {spec:?} ({})",
        slot.key(),
        if names.is_empty() {
            "none are available".to_string()
        } else {
            names.join(", ")
        }
    )
}

/// Whether `spec` names a border that exists, without reading it. For when
/// nothing will be drawn and a mistake should still be reported.
pub fn check(slot: Slot, spec: &str, config: Option<&Path>) -> Result<(), String> {
    if is_path(spec) {
        let path = expand(spec);
        return std::fs::metadata(&path)
            .map(|_| ())
            .map_err(|e| format!("{}: {e}", path.display()));
    }
    if list(slot, config).iter().any(|e| e.name == spec) {
        Ok(())
    } else {
        Err(unknown(slot, spec, config))
    }
}

/// The bytes of the image `spec` names, or why there are none.
pub fn load(slot: Slot, spec: &str, config: Option<&Path>) -> Result<Vec<u8>, String> {
    if is_path(spec) {
        let path = expand(spec);
        return std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display()));
    }

    match list(slot, config).into_iter().find(|e| e.name == spec) {
        Some(Entry {
            source: Source::File(path),
            ..
        }) => std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display())),
        Some(Entry {
            source: Source::Bundled,
            ..
        }) => BORDERS
            .iter()
            .find(|(name, _)| *name == spec)
            .map(|(_, bytes)| bytes.to_vec())
            .ok_or_else(|| format!("{spec:?} is not bundled")),
        None => Err(unknown(slot, spec, config)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[cfg(feature = "bundled-borders")]
    use crate::border::Bitmap;

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("animfetch-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    #[cfg(feature = "bundled-borders")]
    fn the_built_in_borders_are_one_set_for_either_edge() {
        let left = list(Slot::Left, None);
        let bottom = list(Slot::Bottom, None);

        assert!(!left.is_empty(), "no borders were bundled");
        assert_eq!(left, bottom, "an image is for either edge");
        assert!(left.iter().all(|e| e.source == Source::Bundled));

        // Numbered without gaps, from 00.
        let names: Vec<&str> = left.iter().map(|e| e.name.as_str()).collect();
        let expected: Vec<String> = (0..names.len()).map(|i| format!("{i:02}")).collect();
        assert_eq!(names, expected);
    }

    #[test]
    #[cfg(feature = "bundled-borders")]
    fn every_bundled_border_decodes_and_has_something_to_show() {
        // The files are the user's to replace; this is what tells them one is
        // broken, rather than a layout that quietly has no ornament.
        for slot in [Slot::Left, Slot::Bottom] {
            for entry in list(slot, None) {
                let bytes = load(slot, &entry.name, None).unwrap();
                let bitmap = Bitmap::decode(&bytes)
                    .unwrap_or_else(|e| panic!("{slot:?} {}: {e}", entry.name));
                assert!(
                    bitmap.trimmed().is_some(),
                    "{slot:?} {} is fully transparent",
                    entry.name
                );
            }
        }
    }

    #[test]
    #[cfg(feature = "bundled-borders")]
    fn every_built_in_border_is_a_portrait_so_that_turning_one_lays_it_along_the_bottom() {
        // The premise of turning the bottom one: they are drawn upright.
        for entry in list(Slot::Bottom, None) {
            let b = Bitmap::decode(&load(Slot::Bottom, &entry.name, None).unwrap()).unwrap();
            let t = b.trimmed().unwrap();
            assert!(t.h > t.w, "{} is already wider than tall", entry.name);
            let turned = t.rotated_cw();
            assert!(turned.w > turned.h);
        }
    }

    #[test]
    fn the_same_name_is_the_same_image_on_either_edge() {
        let l = load(Slot::Left, "00", None);
        let b = load(Slot::Bottom, "00", None);
        if let (Ok(l), Ok(b)) = (l, b) {
            assert_eq!(l, b, "an image is for either edge");
        }
    }

    #[test]
    fn a_loose_file_of_yours_is_for_either_edge_and_a_folder_is_for_one() {
        let config = scratch("either");
        let border = config.join("border");
        std::fs::create_dir_all(border.join("bottom_border")).unwrap();
        std::fs::write(border.join("loose.png"), b"either").unwrap();
        std::fs::write(border.join("only-bottom.png"), b"x").unwrap();
        std::fs::write(border.join("bottom_border").join("only-bottom.png"), b"bottom").unwrap();
        std::fs::write(border.join("bottom_border").join("low.png"), b"low").unwrap();

        // A loose file is on both edges.
        assert_eq!(load(Slot::Left, "loose", Some(&config)).unwrap(), b"either");
        assert_eq!(load(Slot::Bottom, "loose", Some(&config)).unwrap(), b"either");

        // A folder's file is for its own edge, and wins over a loose one.
        assert_eq!(load(Slot::Bottom, "low", Some(&config)).unwrap(), b"low");
        assert!(load(Slot::Left, "low", Some(&config)).is_err());
        assert_eq!(
            load(Slot::Bottom, "only-bottom", Some(&config)).unwrap(),
            b"bottom"
        );
        assert_eq!(load(Slot::Left, "only-bottom", Some(&config)).unwrap(), b"x");

        std::fs::remove_dir_all(&config).unwrap();
    }

    #[test]
    fn your_own_image_shadows_a_built_in_one_of_the_same_name() {
        let config = scratch("shadow");
        let dir = config.join("border").join("left_border");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("00.png"), b"mine").unwrap();
        std::fs::write(dir.join("zz.png"), b"another").unwrap();
        std::fs::write(dir.join("note.txt"), b"not an image").unwrap();

        let names: Vec<_> = list(Slot::Left, Some(&config))
            .into_iter()
            .map(|e| (e.name, matches!(e.source, Source::File(_))))
            .collect();

        assert!(names.contains(&("00".to_string(), true)), "{names:?}");
        assert!(names.contains(&("zz".to_string(), true)));
        assert!(!names.iter().any(|(n, _)| n == "note"), "only PNGs");
        assert_eq!(
            names.iter().filter(|(n, _)| n == "00").count(),
            1,
            "listed once"
        );
        assert_eq!(load(Slot::Left, "00", Some(&config)).unwrap(), b"mine");

        std::fs::remove_dir_all(&config).unwrap();
    }

    #[test]
    #[cfg(not(feature = "bundled-borders"))]
    fn without_the_feature_nothing_is_built_in_but_your_own_files_still_work() {
        assert!(list(Slot::Left, None).is_empty());
        assert!(list(Slot::Bottom, None).is_empty());

        let err = load(Slot::Left, "00", None).unwrap_err();
        assert!(err.contains("none are available"), "{err}");

        let config = scratch("nobundle");
        let dir = config.join("border").join("left_border");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("mine.png"), b"x").unwrap();
        assert_eq!(list(Slot::Left, Some(&config)).len(), 1);
        std::fs::remove_dir_all(&config).unwrap();
    }

    #[test]
    fn a_path_is_read_as_a_path() {
        let dir = scratch("path");
        let file = dir.join("custom.png");
        std::fs::write(&file, b"bytes").unwrap();

        assert_eq!(
            load(Slot::Left, file.to_str().unwrap(), None).unwrap(),
            b"bytes"
        );
        assert!(is_path("art/x.png") && is_path("X.PNG") && !is_path("01"));
        assert!(load(Slot::Left, "/nonexistent/x.png", None).is_err());

        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn a_mistake_is_reported_without_reading_anything() {
        // Against a folder of our own, so it holds whether or not the images
        // are built in.
        let config = scratch("check");
        let dir = config.join("border").join("left_border");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("mine.png"), b"not even a png").unwrap();

        // It exists, and "exists" is all that is asked: nothing is decoded.
        assert!(check(Slot::Left, "mine", Some(&config)).is_ok());
        assert!(check(Slot::Left, "nope", Some(&config)).is_err());
        assert!(check(Slot::Left, "/nonexistent/x.png", None).is_err());
        // The same name asked another way gives the same words.
        assert_eq!(
            check(Slot::Bottom, "99", Some(&config)).unwrap_err(),
            load(Slot::Bottom, "99", Some(&config)).unwrap_err()
        );

        std::fs::remove_dir_all(&config).unwrap();
    }

    #[test]
    #[cfg(feature = "bundled-borders")]
    fn an_unknown_name_says_what_there_is() {
        let err = load(Slot::Bottom, "no-such-border", None).unwrap_err();
        assert!(
            err.contains("no-such-border") && err.contains("bottom"),
            "{err}"
        );
        assert!(err.contains("00"), "should list what exists: {err}");
    }

    #[test]
    fn a_home_relative_path_is_expanded() {
        // SAFETY of the env read only: the value is whatever the test host has.
        if let Some(home) = std::env::var_os("HOME") {
            assert_eq!(expand("~/a.png"), Path::new(&home).join("a.png"));
        }
        assert_eq!(expand("/abs/a.png"), PathBuf::from("/abs/a.png"));
        assert_eq!(expand("~nobody/a.png"), PathBuf::from("~nobody/a.png"));
    }
}
